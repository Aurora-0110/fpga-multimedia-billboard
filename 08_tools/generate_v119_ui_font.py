"""Reproduce the v119 compact Chinese UI ROMs from pinned OFL Noto CJK.
Outputs embedded Verilog initializers: no runtime font files, OS font dependency
or external CPU. Font source/license are preserved in 07_reference/fonts.
"""
from pathlib import Path
import json, hashlib
from PIL import Image, ImageDraw, ImageFont
ROOT=Path(__file__).resolve().parents[1]
if '01_versions' in ROOT.parts:raise SystemExit('Do not regenerate assets inside frozen archives')
FONT=ROOT/'07_reference/fonts/noto_cjk/NotoSansCJKsc-Medium.otf'
FONT_SHA='ca094f6b0001fb048ca39ddd797a0cdb0179e1e55c6561e111c49c3e6a61d7b7'
MESSAGES=[
 '', '系统控制', 'V119', '功能', '状态',
 '播放模式', '自动轮播', '手动切换', '当前图片', '第1/4张',
 '资源读取', '读取中', '已就绪', '等待中', '故障 00',
 '调节项目', '浏览图片', '调节亮度', '调节对比度', '亮度',
 '+00', '对比度', '100%', '画面叠加', '已开启',
 '已隐藏', '音频输出', '正在输出', '暂无声音', '按键状态',
 '未按下', 'K0按下', 'K1按下', '双键按下', 'K0功能',
 '下一张', '亮度减', '对比度减', 'K1功能', '自动或手动',
 '亮度加', '对比度加', '双键操作', '短按显隐 长按调参', '错误重试',
 '参数异常', '音频选择', '跟随图片', '音乐文件', '广告语音', '暂停播放', '切换音频', '已暂停', '预缓冲', '已结束', '音频故障 00', '播放中', '继续播放', '扩展音频'
]
def glyph_bitmap(font, ch):
 im=Image.new('L',(16,16)); d=ImageDraw.Draw(im)
 if ch!=' ':
  l,t,r,b=font.getbbox(ch)
  assert r-l<=16 and b-t<=16,(ch,(l,t,r,b))
  d.text(((16-(r-l))//2-l,(16-(b-t))//2-t),ch,font=font,fill=255)
 return im.point(lambda x:255 if x>=112 else 0,mode='1')
def main():
 assert hashlib.sha256(FONT.read_bytes()).hexdigest()==FONT_SHA,'Font source identity mismatch'
 font=ImageFont.truetype(str(FONT),14)
 glyphs=list(' 0123456789+-/%?ABCDEFKV')
 for text in MESSAGES:
  for ch in text:
   if ch not in glyphs:glyphs.append(ch)
 assert len(glyphs)<=128 and len(MESSAGES)<=64 and max(map(len,MESSAGES))<=16
 ids={ch:i for i,ch in enumerate(glyphs)}
 rtl=ROOT/'01_project/rtl/visual'
 params=['// Generated by 08_tools/generate_v119_ui_font.py; Noto CJK SIL OFL 1.1.']
 params += [f"localparam [6:0] G_{ord(ch):04X} = 7'd{i}; // U+{ord(ch):04X} {ch}" for i,ch in enumerate(glyphs)]
 (rtl/'media_ui_zh_glyph_ids.vh').write_text('\n'.join(params)+'\n',encoding='utf8')
 rows=[]
 for n in range(128):
  im=glyph_bitmap(font,glyphs[n]) if n<len(glyphs) else Image.new('1',(16,16))
  rows.extend(sum((1<<(15-x)) for x in range(16) if im.getpixel((x,y))) for y in range(16))
 (rtl/'media_ui_zh_font_init.vh').write_text('// Generated 128 x 16 x 16 monochrome font; preserve 07_reference/fonts/noto_cjk/LICENSE.\n'+''.join(f"font_memory[{i}]=16'h{v:04x};\n" for i,v in enumerate(rows)),encoding='utf8')
 cells=[]
 for msg in range(64):
  text=MESSAGES[msg] if msg<len(MESSAGES) else ''
  cells.extend(ids.get(ch,0) for ch in text.ljust(16))
 (rtl/'media_ui_zh_text_init.vh').write_text('// Generated 64 messages x 16 glyphs; blank-filled unused addresses.\n'+''.join(f"text_memory[{i}]=7'd{v};\n" for i,v in enumerate(cells)),encoding='utf8')
 spec={'font_sha256':FONT_SHA,'font_size':14,'threshold':112,'glyphs':glyphs,'glyph_ids':ids,'messages':MESSAGES,'rom_font_bits':len(rows)*16,'rom_text_bits':len(cells)*7,'layout':{'panel':[288,64,992,656],'radius':24,'column_centers':[448,768],'text_origin_y':80,'row_pitch':40,'glyph_size':[16,16],'scale':2,'value_column':7,'columns':18,'rows':14}}
 (ROOT/'03_docs/v119_ui_font_spec.json').write_text(json.dumps(spec,ensure_ascii=False,indent=2),encoding='utf8')
 atlas=Image.new('RGB',(16*48,((len(glyphs)+15)//16)*64),(14,24,38));d=ImageDraw.Draw(atlas)
 for i,ch in enumerate(glyphs):
  x=(i%16)*48;y=(i//16)*64
  d.bitmap((x+8,y+2),glyph_bitmap(font,ch).resize((32,32),Image.Resampling.NEAREST),fill=(240,248,255))
  d.text((x+10,y+39),str(i),fill=(100,216,185))
 out=ROOT/'04_evidence/v119_font_generation';out.mkdir(exist_ok=True)
 atlas.save(out/'glyph_atlas.png')
 (out/'summary.json').write_text(json.dumps({'passed':True,'glyphs':len(glyphs),'messages':len(MESSAGES),'font_sha256':FONT_SHA,'license':'SIL Open Font License 1.1','generated_sha256':{p.relative_to(ROOT).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in [rtl/'media_ui_zh_glyph_ids.vh',rtl/'media_ui_zh_font_init.vh',rtl/'media_ui_zh_text_init.vh']}},indent=2),encoding='utf8')
 print('GENERATED',len(glyphs),'glyphs',len(MESSAGES),'messages; font bits',len(rows)*16,'text bits',len(cells)*7)
if __name__=='__main__':main()

