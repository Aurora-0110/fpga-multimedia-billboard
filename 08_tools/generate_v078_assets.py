"""Reproduce official-logo palette ROM. Default verifies RTL, never overwrites it.
Run with --write-rtl only in a new working version, before synthesis.
"""
from pathlib import Path
import argparse,hashlib,json
from PIL import Image,ImageChops
r=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser();p.add_argument('--write-rtl',action='store_true');a=p.parse_args()
src=r/'06_test_media/four_image_playlist/TF_ROOT/A.BMP'
im=Image.open(src).convert('RGB')
mask=ImageChops.difference(im,Image.new('RGB',im.size,'white')).convert('L').point(lambda v:255 if v>55 else 0)
bbox=mask.getbbox();crop=im.crop(bbox);crop.thumbnail((112,54),Image.Resampling.LANCZOS)
canvas=Image.new('RGB',(112,56),'white');canvas.paste(crop,((112-crop.width)//2,(56-crop.height)//2))
rows=[]
for y in range(56):
 word=0
 for x in range(112):
  rr,g,b=canvas.getpixel((x,y));v=0 if min(rr,g,b)>185 else (2 if rr>g*1.25 and rr>b*1.15 else 1)
  word|=v<<(2*x)
 rows.append(f"  6'd{y}: rowbits=224'h{word:056x};")
text="""`timescale 1ns/1ps
// Derived from official TF A.BMP, generated by tools/generate_v078_assets.py.
// Palette 0=transparent white, 1=official dark blue, 2=official red.
module official_logo(input wire [6:0] x,input wire [5:0] y,output wire [1:0] pixel);
 reg [223:0] rowbits;
 always @* begin case(y)
"""+'\n'.join(rows)+"""
 default:rowbits=0;endcase end
 assign pixel=x<112?((rowbits>>(x*2))&2'b11):2'b00;
endmodule
"""
rtl=r/'01_project/rtl/video/official_logo.v'
if a.write_rtl:rtl.write_text(text,encoding='utf8')
assert rtl.read_text(encoding='utf8')==text,'ROM mismatch; do not silently overwrite during a build'
out=r/'06_test_media/osd_assets';out.mkdir(exist_ok=True);canvas.save(out/'official_logo_preview.png')
rec={'source':str(src.relative_to(r)),'source_sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'crop_bbox':bbox,'canvas':[112,56],'palette':{'0':'transparent','1':'183858','2':'cf1830'},'alpha':12,'alpha_denominator':16,'rom_sha256':hashlib.sha256(rtl.read_bytes()).hexdigest(),'verified':True,'provenance':'Existing official playlist A.BMP (Anlogic logo), inherited unchanged; reduced to 2-bit palette, not exact-color original. No independent redistribution license assertion.'}
(out/'SOURCE.json').write_text(json.dumps(rec,ensure_ascii=False,indent=2)+'\n',encoding='utf8');print(json.dumps(rec,ensure_ascii=False,indent=2))
